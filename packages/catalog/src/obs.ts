import { parseType, type TypedMember } from '@baaportal/s7-types';
import type { ObDefinition } from './types';

// Costruisce le informazioni di avvio; un tipo che non si legge fa fallire subito il caricamento.
function members(fields: readonly (readonly [string, string])[]): TypedMember[] {
  return fields.map(([name, text]) => {
    const r = parseType(text);
    if (!r.ok) throw new Error(`Tipo non valido nel catalogo OB: ${name}: ${text}`);
    return { name, type: r.type };
  });
}

